#!/usr/bin/env python3
"""
YAMIT training script: MLA + Composite-PIT + ReFusion AR+MDM.

Trains the YAMIT model (Model-S or Model-P) on tokenized binary shards with:
  - ReFusion dual loss (L_AR + L_MDM)
  - WSD learning rate scheduler
  - AdamW with PIT-aware param group separation
  - BF16 autocast (Phase 1; FP4 added in Phase 1.5)
  - Periodic validation, save-best checkpointing

Usage:
    python train_yamit.py \
        --data-dir ./tokenized \
        --output-dir ./checkpoints-yamit \
        --token-bytes ./token_bytes.pt \
        --total-tokens 3_000_000_000 \
        --lr 6e-4

Shard format (same as vanilla pipeline):
    .bin: flat little-endian uint32 token IDs
    .idx: little-endian uint64 byte offsets
"""

from __future__ import annotations

import argparse
import copy
import json
import logging
import random
import time
from pathlib import Path

import numpy as np
import torch
from torch.utils.data import DataLoader

from yamit.model import YAMIT, MODEL_S, MODEL_P
from yamit.refusion import forward_process, refusion_loss
from yamit.sampler import generate_refusion, ReFusionSamplerConfig
from yamit.training import (
    ShardedTokenDataset,
    WSDScheduler,
    save_checkpoint,
    load_checkpoint,
)

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s %(levelname)s %(message)s",
    datefmt="%H:%M:%S",
)
log = logging.getLogger(__name__)


# ---------------------------------------------------------------------------
# Token-bytes table builder
# ---------------------------------------------------------------------------

def build_token_bytes_from_tokenizer(
    tokenizer_path: str,
    vocab_size: int,
    max_bytes: int = 16,
    pad_byte_id: int = 256,
) -> torch.Tensor:
    """Build (vocab_size, max_bytes) byte-ID table from a HuggingFace tokenizer.

    WARNING: this is an approximate fallback intended for smoke tests only.
    For spec-conform training, use a token_bytes artifact generated by
    build_composite_tokenizer.py and pass it via --token-bytes.
    """
    try:
        from transformers import AutoTokenizer
    except ImportError:
        raise RuntimeError("transformers package required for tokenizer loading")

    log.info(f"Loading tokenizer from {tokenizer_path}")
    tokenizer = AutoTokenizer.from_pretrained(tokenizer_path, trust_remote_code=True)

    table = torch.full((vocab_size, max_bytes), pad_byte_id, dtype=torch.long)
    n_valid = 0
    n_too_long = 0

    for token_id in range(min(len(tokenizer), vocab_size)):
        try:
            text = tokenizer.decode([token_id], skip_special_tokens=False)
            raw = text.encode("utf-8")
            if len(raw) > max_bytes:
                n_too_long += 1
                continue
            for i, b in enumerate(raw):
                table[token_id, i] = b
            n_valid += 1
        except Exception:
            pass

    log.warning(
        f"Token bytes table: {n_valid} valid, {n_too_long} too long (>16 bytes), "
        f"{vocab_size - n_valid - n_too_long} missing/failed"
    )
    return table


def load_artifact_meta(token_bytes_path: str | None) -> dict | None:
    """Load tokenizer artifact metadata adjacent to token_bytes if available."""
    if not token_bytes_path:
        return None
    p = Path(token_bytes_path)
    meta_path = p.with_name("artifact_meta.json")
    if not meta_path.exists():
        return None
    try:
        with open(meta_path) as f:
            return json.load(f)
    except Exception as e:
        log.warning(f"Failed to read artifact meta at {meta_path}: {e}")
        return None


# ---------------------------------------------------------------------------
# YAMIT-specific param groups
# ---------------------------------------------------------------------------

def yamit_param_groups(
    model: YAMIT,
    weight_decay: float,
) -> list[dict]:
    """Separate parameters into decay / no-decay groups.

    No weight decay on:
      - All PIT parameters (byte_memory, byte_chol_raw, token_embed)
      - mask_embed
      - token_up_gate
      - All norms
      - All biases
      - token_out_bias
    """
    decay = []
    no_decay = []

    for name, param in model.named_parameters():
        if not param.requires_grad:
            continue
        # No-decay: PIT params, embeddings, norms, biases, gates
        if any(kw in name for kw in [
            "byte_memory", "byte_chol_raw", "token_embed",
            "special_patterns", "token_up_gate", "token_out_bias",
            "norm", "bias",
        ]):
            no_decay.append(param)
        else:
            decay.append(param)

    log.info(
        f"Param groups: {len(decay)} decay params, {len(no_decay)} no-decay params"
    )
    return [
        {"params": decay, "weight_decay": weight_decay},
        {"params": no_decay, "weight_decay": 0.0},
    ]


# ---------------------------------------------------------------------------
# Evaluation with ReFusion
# ---------------------------------------------------------------------------

@torch.no_grad()
def evaluate_yamit(
    model: YAMIT,
    val_loader: DataLoader,
    mask_token_id: int,
    max_batches: int = 50,
    device: torch.device = torch.device("cuda"),
) -> dict[str, float]:
    """Evaluate with ReFusion forward process (same as training)."""
    model.eval()
    total_loss = 0.0
    total_ar = 0.0
    total_mdm = 0.0
    n_batches = 0

    device_type = "cuda" if device.type == "cuda" else "cpu"

    for batch in val_loader:
        if n_batches >= max_batches:
            break
        input_ids = batch["input_ids"].to(device)
        attention_mask = torch.ones_like(input_ids)

        # ReFusion forward process.
        fp = forward_process(
            input_ids,
            attention_mask,
            mask_token_id=mask_token_id,
            boundary_token_id=model.cfg.eos_token_id,
        )

        with torch.autocast(device_type=device_type, dtype=torch.bfloat16):
            logits = model(fp.input_ids, position_ids=fp.position_ids)

        loss, ar, mdm = refusion_loss(
            logits, fp.labels, fp.masked_indices, fp.p_masks, fp.answer_lengths
        )

        total_loss += loss.item()
        total_ar += ar.item()
        total_mdm += mdm.item()
        n_batches += 1

    model.train()
    n = max(1, n_batches)
    return {
        "val_loss": total_loss / n,
        "val_ar": total_ar / n,
        "val_mdm": total_mdm / n,
    }


@torch.no_grad()
def evaluate_generation_samples(
    model: YAMIT,
    val_loader: DataLoader,
    args,
    device: torch.device,
    decode_token_ids=None,
) -> tuple[dict[str, float], list[dict[str, str]]]:
    """Run generation samples + sampler metrics during eval.

    Returns:
        metrics: averaged sampler metrics
        samples: list of printable prompt/gen/ref strings (or token IDs)
    """
    model.eval()

    sampler_cfg = ReFusionSamplerConfig(
        slot_size=args.sample_slot_size,
        serial_num_blocks=args.sample_serial_num_blocks,
        slot_threshold=args.sample_slot_threshold,
        token_threshold=args.sample_token_threshold,
        max_refinement_iters=(
            None if args.sample_max_refinement_iters <= 0
            else args.sample_max_refinement_iters
        ),
        temperature=args.sample_temperature,
        force_accept_fallback=True,
    )

    n_done = 0
    slot_accept_sum = 0.0
    verify_sum = 0.0
    iter_sum = 0.0
    eos_hits = 0
    token_match_sum = 0.0
    token_match_count = 0
    sample_logs: list[dict[str, str]] = []

    for batch in val_loader:
        if n_done >= args.eval_samples:
            break

        batch_ids = batch["input_ids"]  # on CPU
        bsz = batch_ids.shape[0]

        for bi in range(bsz):
            if n_done >= args.eval_samples:
                break

            seq = batch_ids[bi]
            if seq.numel() < 4:
                continue

            prompt_len = min(args.sample_prompt_len, max(1, seq.numel() - 1))
            gen_len = min(args.sample_gen_len, max(1, seq.numel() - prompt_len))
            if gen_len <= 0:
                continue

            prompt = seq[:prompt_len].to(device).unsqueeze(0)
            ref = seq[prompt_len : prompt_len + gen_len]

            out, st = generate_refusion(
                model,
                prompt,
                gen_length=gen_len,
                mask_token_id=model.cfg.mask_token_id,
                eos_token_id=model.cfg.eos_token_id,
                config=sampler_cfg,
            )
            gen = out[0, prompt_len : prompt_len + gen_len].detach().cpu()

            slot_accept_sum += st.slot_accept_rate
            verify_sum += st.verification_pass_rate
            iter_sum += st.iterations_per_generated_token
            eos_hits += int(st.eos_hit)

            m = min(gen.numel(), ref.numel())
            if m > 0:
                token_match = (gen[:m] == ref[:m]).float().mean().item()
                token_match_sum += token_match
                token_match_count += 1
            else:
                token_match = 0.0

            if decode_token_ids is not None:
                prompt_str = decode_token_ids(prompt[0].detach().cpu())
                gen_str = decode_token_ids(gen)
                ref_str = decode_token_ids(ref)
            else:
                prompt_str = str(prompt[0].detach().cpu().tolist()[:64])
                gen_str = str(gen.tolist()[:64])
                ref_str = str(ref.tolist()[:64])

            sample_logs.append(
                {
                    "prompt": prompt_str,
                    "generated": gen_str,
                    "reference": ref_str,
                    "token_match": f"{token_match:.3f}",
                }
            )

            n_done += 1

    n = max(1, n_done)
    metrics = {
        "gen_slot_accept_rate": slot_accept_sum / n,
        "gen_verification_pass_rate": verify_sum / n,
        "gen_iterations_per_token": iter_sum / n,
        "gen_eos_hit_rate": float(eos_hits) / n,
        "gen_token_match_rate": (
            token_match_sum / max(1, token_match_count)
        ),
        "gen_samples": float(n_done),
    }
    model.train()
    return metrics, sample_logs


# ---------------------------------------------------------------------------
# Training loop
# ---------------------------------------------------------------------------

def train(args):
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    log.info(f"Device: {device}")

    # ── Config ──
    if args.model_size == "S":
        cfg = copy.deepcopy(MODEL_S)
    elif args.model_size == "P":
        cfg = copy.deepcopy(MODEL_P)
    else:
        raise ValueError(f"Unknown model size: {args.model_size}")

    # Optional tokenizer decode helper for generation sample logging.
    decode_token_ids = None
    if args.sample_decode and args.tokenizer:
        try:
            from transformers import AutoTokenizer

            tok = AutoTokenizer.from_pretrained(args.tokenizer, trust_remote_code=True)

            def _decode(ids: torch.Tensor) -> str:
                return tok.decode(ids.tolist(), skip_special_tokens=False)

            decode_token_ids = _decode
            log.info("Loaded tokenizer for eval sample decoding")
        except Exception as e:
            log.warning(f"Could not load tokenizer for decoding samples: {e}")

    # ── Token bytes ──
    token_bytes_path = args.token_bytes
    artifact_meta = None
    if token_bytes_path and Path(token_bytes_path).exists():
        log.info(f"Loading token bytes from {token_bytes_path}")
        token_bytes = torch.load(token_bytes_path, weights_only=True)
        artifact_meta = load_artifact_meta(token_bytes_path)
    elif args.tokenizer and args.allow_approx_tokenizer_bytes:
        log.info(f"Building token bytes from tokenizer: {args.tokenizer}")
        token_bytes = build_token_bytes_from_tokenizer(
            args.tokenizer, cfg.vocab_size, cfg.max_bytes_per_token
        )
        # Cache for next time.
        if token_bytes_path:
            torch.save(token_bytes, token_bytes_path)
            log.info(f"Saved token bytes to {token_bytes_path}")
    else:
        raise ValueError(
            "Missing token-bytes mapping. For spec-conform training, pass "
            "--token-bytes <path>. If you only want a quick smoke test, pass "
            "--tokenizer <name_or_path> --allow-approx-tokenizer-bytes."
        )

    # Sync config vocab/special IDs with tokenizer artifacts when present.
    cfg.vocab_size = int(token_bytes.shape[0])
    special_token_ids: list[int] = []
    if artifact_meta:
        resolved = artifact_meta.get("special_tokens", {})
        for key in ("mask", "eos", "pad", "bos", "unk"):
            val = resolved.get(key)
            if val is not None and isinstance(val, int):
                special_token_ids.append(val)
        if resolved.get("mask") is not None:
            cfg.mask_token_id = int(resolved["mask"])
        if resolved.get("eos") is not None:
            cfg.eos_token_id = int(resolved["eos"])
        if resolved.get("pad") is not None:
            cfg.pad_token_id = int(resolved["pad"])
        # Also include any extra special tokens from the artifact.
        for tok_id in artifact_meta.get("new_special_token_ids", {}).values():
            if isinstance(tok_id, int):
                special_token_ids.append(tok_id)
        # Include all added tokens (they're all control tokens without byte structure).
        bpe_vocab_size = artifact_meta.get("bpe_vocab_size")
        if bpe_vocab_size is not None:
            # Added tokens start at bpe_vocab_size and go up to unpadded_vocab_size.
            unpadded = artifact_meta.get("unpadded_vocab_size", cfg.vocab_size)
            for tid in range(int(bpe_vocab_size), int(unpadded)):
                special_token_ids.append(tid)
        special_token_ids = sorted(set(special_token_ids))
        log.info(
            "Tokenizer artifact config: "
            f"vocab_size={cfg.vocab_size}, mask={cfg.mask_token_id}, "
            f"eos={cfg.eos_token_id}, pad={cfg.pad_token_id}, "
            f"special_tokens={len(special_token_ids)}"
        )

    # ── Model ──
    model = YAMIT(cfg, token_bytes=token_bytes, special_token_ids=special_token_ids or None).to(device)
    log.info(f"Model-{args.model_size} params: {model.param_count():,}")

    # torch.compile for speed.
    compiled_model = model
    if hasattr(torch, "compile") and device.type == "cuda" and not args.no_compile:
        log.info("Compiling model with torch.compile...")
        compiled_model = torch.compile(model)

    # ── Optimizer ──
    param_groups = yamit_param_groups(model, args.weight_decay)
    optimizer = torch.optim.AdamW(
        param_groups,
        lr=args.lr,
        betas=(0.9, 0.95),
        eps=1e-8,
        fused=(device.type == "cuda"),
    )

    # ── Steps ──
    tokens_per_step = args.micro_batch_size * args.seq_len
    total_steps = args.total_tokens // tokens_per_step
    log.info(
        f"Total steps: {total_steps:,}  "
        f"({args.total_tokens:,} tokens / {tokens_per_step:,} per step)"
    )

    # ── Scheduler ──
    scheduler = WSDScheduler(
        optimizer=optimizer,
        peak_lr=args.lr,
        warmup_steps=args.warmup_steps,
        total_steps=total_steps,
        decay_fraction=args.decay_fraction,
    )

    # ── Data ──
    train_dir = str(Path(args.data_dir) / "train")
    val_dir = str(Path(args.data_dir) / "val")

    train_dataset = ShardedTokenDataset(
        train_dir, seq_len=args.seq_len, shuffle_shards=True
    )
    train_loader = DataLoader(
        train_dataset,
        batch_size=args.micro_batch_size,
        num_workers=args.num_workers,
        pin_memory=True,
        drop_last=True,
    )

    val_dataset = ShardedTokenDataset(
        val_dir, seq_len=args.seq_len, shuffle_shards=False
    )
    val_loader = DataLoader(
        val_dataset,
        batch_size=args.micro_batch_size,
        num_workers=1,
        pin_memory=True,
        drop_last=True,
    )

    # ── Resume ──
    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    start_step = 0
    best_val_loss = float("inf")
    last_ckpt = output_dir / "last.pt"
    if last_ckpt.exists() and args.resume:
        ckpt = load_checkpoint(str(last_ckpt), model, optimizer)
        start_step = ckpt.get("step", 0)
        best_val_loss = ckpt.get("best_val_loss", float("inf"))
        log.info(f"Resuming from step {start_step}, best val loss {best_val_loss:.4f}")

    # ── Train ──
    model.train()
    device_type = "cuda" if device.type == "cuda" else "cpu"
    step = start_step
    tokens_seen = step * tokens_per_step
    mask_token_id = cfg.mask_token_id
    grad_clip = args.grad_clip

    running_loss = 0.0
    running_ar = 0.0
    running_mdm = 0.0
    running_count = 0
    t0 = time.time()
    eval_count = 0

    log.info(f"Starting YAMIT training from step {step}")
    train_iter = iter(train_loader)

    while step < total_steps:
        try:
            batch = next(train_iter)
        except StopIteration:
            train_iter = iter(train_loader)
            batch = next(train_iter)

        input_ids = batch["input_ids"].to(device, non_blocking=True)
        attention_mask = torch.ones_like(input_ids)

        # ── ReFusion forward process ──
        fp = forward_process(
            input_ids,
            attention_mask,
            mask_token_id=mask_token_id,
            boundary_token_id=cfg.eos_token_id,
        )

        # ── LR step ──
        lr = scheduler.step(step)

        # ── Forward ──
        with torch.autocast(device_type=device_type, dtype=torch.bfloat16):
            logits = compiled_model(fp.input_ids, position_ids=fp.position_ids)

        # Loss (computed in FP32).
        loss, ar_loss, mdm_loss = refusion_loss(
            logits, fp.labels, fp.masked_indices, fp.p_masks, fp.answer_lengths
        )

        # ── Backward ──
        loss.backward()

        if grad_clip > 0:
            grad_norm = torch.nn.utils.clip_grad_norm_(
                model.parameters(), grad_clip
            ).item()
        else:
            grad_norm = 0.0

        optimizer.step()
        optimizer.zero_grad(set_to_none=True)

        # ── Stats ──
        running_loss += loss.item()
        running_ar += ar_loss.item()
        running_mdm += mdm_loss.item()
        running_count += 1
        tokens_seen += tokens_per_step
        step += 1

        # ── Logging ──
        if step % args.log_interval == 0:
            n = max(1, running_count)
            avg_loss = running_loss / n
            avg_ar = running_ar / n
            avg_mdm = running_mdm / n
            elapsed = time.time() - t0
            tok_per_sec = tokens_seen / max(1, elapsed)
            log.info(
                f"step={step:>7d} | "
                f"loss={avg_loss:.4f} (ar={avg_ar:.4f} mdm={avg_mdm:.4f}) | "
                f"lr={lr:.2e} | "
                f"gnorm={grad_norm:.2f} | "
                f"tok={tokens_seen:,.0f} | "
                f"tok/s={tok_per_sec:,.0f}"
            )
            running_loss = 0.0
            running_ar = 0.0
            running_mdm = 0.0
            running_count = 0

        # ── Evaluation ──
        if step % args.eval_interval == 0:
            eval_count += 1
            metrics = evaluate_yamit(
                model, val_loader, mask_token_id, max_batches=50, device=device
            )
            log.info(
                f"step={step:>7d} | "
                f"val_loss={metrics['val_loss']:.4f} "
                f"(ar={metrics['val_ar']:.4f} mdm={metrics['val_mdm']:.4f}) | "
                f"best={best_val_loss:.4f}"
            )
            if metrics["val_loss"] < best_val_loss:
                best_val_loss = metrics["val_loss"]
                save_checkpoint(
                    str(output_dir / "best.pt"),
                    model, optimizer, step, best_val_loss,
                    config=vars(args),
                )
                log.info(f"New best model saved (val_loss={best_val_loss:.4f})")

            # Optional generation samples + sampler telemetry.
            if args.eval_samples > 0 and (eval_count % max(1, args.gen_eval_every) == 0):
                try:
                    g_metrics, g_samples = evaluate_generation_samples(
                        model=model,
                        val_loader=val_loader,
                        args=args,
                        device=device,
                        decode_token_ids=decode_token_ids,
                    )
                    log.info(
                        "sampler | "
                        f"slot_accept={g_metrics['gen_slot_accept_rate']:.3f} | "
                        f"verify_pass={g_metrics['gen_verification_pass_rate']:.3f} | "
                        f"iters/tok={g_metrics['gen_iterations_per_token']:.3f} | "
                        f"eos_hit={g_metrics['gen_eos_hit_rate']:.3f} | "
                        f"tok_match={g_metrics['gen_token_match_rate']:.3f} | "
                        f"n={int(g_metrics['gen_samples'])}"
                    )
                    for i, s in enumerate(g_samples):
                        log.info(f"sample[{i}] prompt: {s['prompt']}")
                        log.info(f"sample[{i}] gen:    {s['generated']}")
                        log.info(f"sample[{i}] ref:    {s['reference']}")
                        log.info(f"sample[{i}] match:  {s['token_match']}")
                except Exception as e:
                    log.warning(f"Generation eval failed at step {step}: {e}")

        # ── Periodic save ──
        if step % args.save_interval == 0:
            save_checkpoint(
                str(output_dir / "last.pt"),
                model, optimizer, step, best_val_loss,
                config=vars(args),
            )

    # ── Final ──
    save_checkpoint(
        str(output_dir / "last.pt"),
        model, optimizer, step, best_val_loss,
        config=vars(args),
    )

    metrics = evaluate_yamit(
        model, val_loader, mask_token_id, max_batches=100, device=device
    )
    log.info(
        f"Training complete. "
        f"Final val_loss={metrics['val_loss']:.4f}, best={best_val_loss:.4f}"
    )

    elapsed = time.time() - t0
    summary = {
        "model": f"YAMIT Model-{args.model_size}",
        "total_steps": step,
        "total_tokens": tokens_seen,
        "best_val_loss": best_val_loss,
        "final_val_loss": metrics["val_loss"],
        "final_val_ar": metrics["val_ar"],
        "final_val_mdm": metrics["val_mdm"],
        "elapsed_seconds": elapsed,
        "tokens_per_second": tokens_seen / max(1, elapsed),
        "model_params": model.param_count(),
    }
    summary_path = output_dir / "training_summary.json"
    with open(summary_path, "w") as f:
        json.dump(summary, f, indent=2)
    log.info(f"Training summary written to {summary_path}")


def main():
    parser = argparse.ArgumentParser(description="YAMIT training with ReFusion AR+MDM")

    # Data
    parser.add_argument("--data-dir", type=str, required=True,
                        help="Tokenized data directory (train/ and val/ subdirs)")
    parser.add_argument("--output-dir", type=str, default="./checkpoints-yamit")
    parser.add_argument("--token-bytes", type=str, default=None,
                        help="Path to token_bytes.pt (vocab_size, 16) tensor")
    parser.add_argument("--tokenizer", type=str, default=None,
                        help="HuggingFace tokenizer name/path for approximate byte-table fallback")
    parser.add_argument(
        "--allow-approx-tokenizer-bytes",
        action="store_true",
        help="Allow approximate token-bytes building from tokenizer.decode() for smoke tests",
    )

    # Model
    parser.add_argument("--model-size", type=str, default="S", choices=["S", "P"],
                        help="Model size: S (~130M) or P (~347M)")

    # Training
    parser.add_argument("--total-tokens", type=int, default=3_000_000_000)
    parser.add_argument("--micro-batch-size", type=int, default=8)
    parser.add_argument("--seq-len", type=int, default=4096)
    parser.add_argument("--lr", type=float, default=6e-4)
    parser.add_argument("--weight-decay", type=float, default=0.1)
    parser.add_argument("--grad-clip", type=float, default=1.0)
